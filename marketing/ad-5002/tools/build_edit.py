# الأزمنة بالمصدر (IMG_5002 بعد تحويله إلى 30 إطاراً/ث). كل قطعٍ إمّا على صمتٍ مقيس
# (silencedetect) أو حدّ كلمةٍ من Whisper، ومخفيٌّ بمشهد قطعٍ أو بتغيير حجم اللقطة.
#   python tools/build_edit.py
import json, numpy as np, soundfile as sf

KEEP = [  # (من، إلى) — ما يُحذف بينها: المقدّمة، تكرار «تطبيق وجيز»، الكهرباء، «بعد تنزّل…»،
          # «بعد ما تعمل الحساب…»، «آه»، والوقفات الطويلة
    (7.02, 14.93), (15.17, 15.95), (16.64, 28.48), (35.62, 40.06), (41.16, 42.62), (43.90, 47.30),
    (47.50, 48.64), (49.30, 51.47), (51.68, 53.46), (53.78, 54.94), (55.45, 56.66), (56.88, 57.70)]
END_CARD = 3.0
XF = 0.012  # تلاشٍ متقاطع على كل وصلة صوت

# الخريطة: زمن المصدر → زمن المخرَج
segs, o = [], 0.0
for a, b in KEEP: segs.append({'src': a, 'srcEnd': b, 'out': round(o, 3)}); o += b - a
SPEECH = o
def out(t):
    for s in segs:
        if s['src'] - 1e-6 <= t <= s['srcEnd'] + 1e-6: return round(s['out'] + t - s['src'], 3)
    raise ValueError(f'{t} not kept')

# الترجمة: [الكلمة، بداية المصدر، مفتاحية؟] — النص مصحَّح (آبل ستور، براحتك، بأقل سعر)
P = [
    [('مشكلة', 8.66, 1), ('التوصيل', 9.18, 1), ('كانت', 9.74, 0), ('واحدة', 10.20, 0), ('من', 10.40, 0), ('المشاكل', 10.48, 0)],
    [('اللي', 10.72, 0), ('قاعدة', 10.90, 0), ('تعيقني', 11.14, 0), ('دايماً', 11.50, 0), ('في', 11.78, 0), ('شغلي', 12.28, 0)],
    [('لكن', 12.72, 0), ('حالياً', 13.14, 0), ('لقيت', 13.62, 0), ('الحل', 14.06, 1), ('المثالي', 14.38, 1)],
    [('في', 15.20, 0), ('تطبيق', 15.24, 0), ('وجيز', 15.54, 1)],
    [('بيتيح', 16.66, 0), ('ليك', 16.95, 0), ('خدمات', 17.18, 0), ('التوصيل', 17.80, 0)],
    [('بسرعة', 18.34, 0), ('وسهولة', 18.80, 0), ('وكمان', 19.68, 0), ('ضمان', 20.10, 0)],
    [('الحاجة', 20.52, 0), ('المميزة', 21.10, 1), ('في', 21.44, 0), ('وجيز', 21.48, 0), ('كذلك', 21.72, 0)],
    [('إنو', 22.14, 0), ('بيقدر', 22.46, 0), ('يخليك', 22.88, 0), ('تحدد', 23.44, 1), ('السعر', 23.86, 1)],
    [('اللي', 24.26, 0), ('إنت', 24.42, 0), ('عاوزو', 24.56, 0), ('بكل', 24.98, 0), ('أريحية', 25.72, 0)],
    [('يعني', 26.32, 0), ('تقدر', 26.68, 0), ('تتناقش', 26.94, 1), ('مع', 27.32, 0), ('الكابتن', 27.46, 1)],
    [('عشان', 27.92, 0), ('يوصلك', 28.16, 0)],
    [('فالموضوع', 35.64, 0), ('بسيط', 36.22, 1), ('جداً', 36.48, 1)],
    [('كل', 36.80, 0), ('اللي', 37.08, 0), ('عليك', 37.26, 0), ('تدخل', 37.54, 0), ('على', 37.84, 0), ('آبل ستور', 38.00, 1)],
    [('وتنزّل', 39.01, 0), ('تطبيق', 39.38, 0), ('وجيز', 39.74, 1)],
    [('تعمل', 41.18, 0), ('ليك', 41.50, 0), ('حساب', 41.62, 1), ('أكاونت', 41.90, 0), ('فيه', 42.20, 0)],
    [('مرحباً', 43.92, 0), ('بيك', 44.36, 0), ('بتعتبر', 44.52, 0), ('رسمياً', 44.90, 0)],
    [('بقيت', 45.28, 0), ('واحد', 45.72, 0), ('من', 46.14, 0), ('عائلة', 46.18, 1), ('وجيز', 46.58, 1)],
    [('وبكده', 47.54, 0), ('بتقدر', 48.14, 0), ('تطلب', 49.40, 1), ('براحتك', 49.98, 0)],
    [('وتستلم', 50.50, 1), ('براحتك', 51.30, 0)],
    [('وكمان', 52.18, 0), ('بأقل', 52.66, 0), ('سعر', 52.96, 0)],
    [('وبضمان', 53.82, 0), ('وسرعة', 54.38, 0)],
    [('خلّيك', 55.50, 0), ('معانا', 56.10, 0), ('إنت', 56.50, 0)],
    [('من', 56.95, 0), ('أسرة', 57.16, 1), ('وجيز', 57.40, 1)],
]
caps = []
for ph in P:
    words = [{'w': w, 's': out(s), 'k': k} for w, s, k in ph]
    caps.append({'s': words[0]['s'], 'words': words})
for i, c in enumerate(caps):
    nxt = caps[i + 1]['s'] if i + 1 < len(caps) else SPEECH
    c['e'] = round(min(nxt, c['words'][-1]['s'] + 0.75), 3)

# مشاهد القطع (بزمن المصدر) — كل وصلةٍ في الكلام تقع تحت مشهد قطع أو تغيير حجم
CUT = [('logo', 15.50, 17.10), ('price', 23.44, 26.24), ('offers', 26.32, 28.48, 36.10), ('badges', 37.84, 40.06, 41.60), ('tracking', 47.50, 51.47)]
cuts = []
for c in CUT:
    if len(c) == 3: cuts.append({'k': c[0], 's': out(c[1]), 'e': out(c[2])})
    else:  # يمتدّ عبر الوصلة إلى ما بعدها
        cuts.append({'k': c[0], 's': out(c[1]), 'e': out(c[3])})
# حجم اللقطة: 1.06 أساس، 1.15 قريب — يتبدّل على رؤوس الجمل وعند كل وصلة ظاهرة
SCALE = [(7.02, 1.15), (8.66, 1.06), (12.72, 1.15), (15.17, 1.06), (17.10, 1.15), (20.52, 1.06), (36.10, 1.15), (41.60, 1.06),
         (43.90, 1.15), (51.68, 1.06), (53.78, 1.15), (55.45, 1.06), (56.88, 1.15)]
scale = [{'t': out(t), 'z': z} for t, z in SCALE]
joins = [s['out'] for s in segs[1:]]

ed = {'speech': round(SPEECH, 3), 'dur': round(SPEECH + END_CARD, 3), 'segs': segs, 'caps': caps, 'cuts': cuts, 'scale': scale, 'joins': joins,
      'hook': {'s': 0.0, 'word': out(7.66), 'e': out(8.62)}}
json.dump(ed, open('edit.json', 'w', encoding='utf8'), ensure_ascii=False, indent=1)

# الصوت المحرَّر: القطع مع تلاشٍ متقاطع، ثم صمتٌ لبطاقة الختام
v, sr = sf.read('src/voice_clean.wav', dtype='float32')
# تلاشٍ خروجٍ ودخول (6ms لكلٍّ) على كل وصلة بلا تداخل: الطول = مجموع المقاطع بالضبط، فلا تنزاح الترجمة
n = int(XF / 2 * sr); parts = []
for i, (a, b) in enumerate(KEEP):
    x = v[int(round(a * sr)):int(round(a * sr)) + int(round((b - a) * sr))].copy()
    r = np.linspace(0, 1, n, dtype=np.float32)
    if i: x[:n] *= r
    if i < len(KEEP) - 1: x[-n:] *= r[::-1]
    parts.append(x)
res = np.concatenate(parts)
res = np.concatenate([res, np.zeros(int(END_CARD * sr), np.float32)])
sf.write('src/voice_edit.wav', res, sr)
print(f'speech {SPEECH:.2f}s + end {END_CARD}s = {ed["dur"]:.2f}s; {len(caps)} captions; joins at', ', '.join(f'{j:.2f}' for j in joins))
print('cutaways', [(c['k'], c['s'], c['e']) for c in cuts])

/**
 * 📩 رسالة قبول الكابتن — نصٌّ واحد يُرسَل واتساب ويُنسَخ من اللوحة.
 *
 * لماذا واتساب لا إشعار التطبيق وحده: الكابتن المقبول **لم يدخل التطبيق
 * بعد** — سجّل ثم انتظر. فإشعارٌ داخل التطبيق قد لا يراه أحد. ورقم واتسابه
 * مطلوبٌ في نموذج الانتساب أصلاً، فهو القناة التي تصله فعلاً.
 *
 * ⚠️ **لا كلمة مرور في الرسالة، ولا يمكن أن تكون.** كلمة المرور مخزَّنة
 *    مُعمّاة (bcrypt) ولا تُقرأ حتى من قاعدة البيانات — وهذا صحيحٌ أمنياً.
 *    والكابتن هو من اختارها عند التسجيل. فالرسالة تذكّره بمعرّف الدخول
 *    وتدلّه على «نسيت كلمة المرور» إن نسيها. أي رسالة تَعِد بإرسال كلمة
 *    المرور تَعِد بما لا يُنفَّذ.
 *
 * ولا رموز تعبيرية: التنسيق بنجمتَي واتساب للعريض وفواصل نصّية.
 *
 * 💰 والمحفظة تُشرَح صراحةً لأنها أكثر ما يُفاجئ الكابتن: الأجرة تُقبض منه
 *    كاملةً من العميل، والعمولة تتراكم **ديناً** في محفظته (wallet_balance
 *    يُنقَص عند كل تسليم في routes/orders.js)، فإذا بلغ الدَّين الحدّ
 *    الائتماني **توقّف استقبال الطلبات** حتى يسدّد. من لا يعرف هذا يظنّ
 *    التطبيق تعطّل، ويتصل بالدعم غاضباً — وهو محقّ: لم يُقَل له.
 */

/** يُظهر الرقم بصيغة محلية مقروءة (09xxxxxxxx) بدل 2499xxxxxxxx. */
function localPhone(phone) {
    const p = String(phone || '').replace(/\D/g, '');
    if (!p) return '';
    if (p.startsWith('249')) return '0' + p.slice(3);
    if (p.startsWith('0')) return p;
    return p;
}

/**
 * @param {object} o
 * @param {string} o.name          اسم الكابتن كما سجّله
 * @param {string} [o.phone]       هاتف الحساب — معرّف الدخول الأساسي
 * @param {string} [o.email]       بريد الحساب — معرّف بديل
 * @param {string} [o.appLink]     رابط تحميل التطبيق (أندرويد)
 * @param {string} [o.appLinkIos]  رابط App Store — الرسالة تصل واتساب ولا
 *                                 نعرف جهاز الكابتن، فنعطي الرابطين معاً
 * @param {string} [o.supportPhone] رقم الدعم
 * @param {number} [o.commissionRate] نسبة عمولة التطبيق (0.15 = ١٥٪)
 * @param {number} [o.creditLimit]   حدّ المديونية (سالب) — عنده يتوقّف استقبال الطلبات
 * @returns {string} نصّ الرسالة جاهزاً للإرسال
 */
function buildCaptainApprovalMessage(o) {
    const opts = o || {};
    const name = String(opts.name || '').trim() || 'الكابتن';
    const phone = localPhone(opts.phone);
    const email = String(opts.email || '').trim();
    // 📲 روابط المتاجر: الإعدادات أولاً، وإلا الرابطان المعروفان.
    //
    // ⚠️ كان السطر يسقط كلّه حين يخلو الإعداد — وappStoreLink فارغٌ في
    //    إعدادات المدينتين فعلاً، فكل كابتن مقبول تصله رسالةٌ برابط
    //    أندرويد وحده. وصاحب الآيفون يُقال له «حمّل التطبيق» ولا يُعطى
    //    من أين. الرابط ثابتٌ ومعروف، فغيابه من الإعدادات لا يبرّر حذفه.
    const appLink = String(opts.appLink || '').trim()
        || 'https://play.google.com/store/apps/details?id=com.wajeezsd.app';
    const appLinkIos = String(opts.appLinkIos || '').trim()
        || 'https://apps.apple.com/app/id6807840888';
    const support = localPhone(opts.supportPhone);

    const pct = Math.round((Number(opts.commissionRate) || 0.15) * 100);
    // الحدّ يُخزَّن سالباً (-8500) والكابتن يفهمه مبلغاً موجباً يدين به
    const debtCap = Math.abs(Number(opts.creditLimit) || 0);

    // معرّف الدخول: الهاتف أولاً لأنه ما يحفظه الكابتن، والبريد بديلاً
    const loginLines = [];
    if (phone) loginLines.push(`• رقم الهاتف: ${phone}`);
    if (email) loginLines.push(`• أو البريد: ${email}`);
    if (!loginLines.length) loginLines.push('• استخدم رقم هاتفك الذي سجّلت به');

    const lines = [
        `*مبروك ${name} — اتقبلت كابتن في وجيز*`,
        '',
        'راجعنا طلبك ووثائقك، وحسابك جاهز للشغل من هسّع.',
        '',
        '*دخولك للتطبيق*',
        ...loginLines,
        '• كلمة السر: هي الكتبتها وقت التسجيل',
        '',
        'نسيتها؟ اضغط "نسيت كلمة المرور" في شاشة الدخول ويجيك كود في تلفونك.',
        '',
        '*أول شغلة تعملها*',
        '1. افتح التطبيق وادخل من "دخول الكابتن".',
        '2. شغّل زرّ "متصل" فوق — وانت مقفول ما بتجيك طلبات.',
        '3. اسمح للتطبيق بالموقع والإشعارات، لأنو بدونها الطلبات ما بتوصلك.',
        '4. لمن يجيك طلب: اقبلو، استلم من المحل، ووصّل للزبون واضغط "تم التسليم".',
        ''
    ];

    // 💰 المحفظة — أكثر ما يُفاجئ الكابتن فيُقال له قبل أن يقع فيه.
    //    الأرقام من إعدادات مدينته لا مكتوبةً في النصّ: تختلف بين المدن
    //    وتتغيّر من اللوحة، ورقمٌ قديمٌ في رسالةٍ أسوأ من لا رقم.
    lines.push('*المحفظة والتوريد — اقراها كويس*');
    lines.push(`• الأجرة بتقبضها كاملة من الزبون، وعمولة التطبيق ${pct}% بتتسجّل عليك دين في المحفظة.`);
    if (debtCap) {
        lines.push(`• لمن الدين يوصل ${debtCap.toLocaleString('en-US')} ج.س بتوقف عنك الطلبات لحدي ما تسدّد.`);
    } else {
        lines.push('• لمن الدين يوصل الحد المسموح بتوقف عنك الطلبات لحدي ما تسدّد.');
    }
    lines.push('• تابع رصيدك من "المحفظة" في التطبيق، وسدّد قبل ما توصل الحد عشان ما يقطع شغلك.');
    lines.push('• بعد ما تحوّل، ارفع رقم الإشعار وصورة الإيصال من التطبيق وبتراجعها الإدارة.');
    lines.push('');
    lines.push('*حاجات تخليك كابتن كويس*');
    lines.push('• خلّي بطاريتك ونتك دايماً شغالين — تأخير الطلب بينزّل تقييمك.');
    lines.push('• ما تلغي طلب بعد ما تقبلو إلا لظرف طارئ وبعد ما ترجع للإدارة، الإلغاء المتكرر بجمّد الحساب.');

    // 📲 الرابطان معاً: الرسالة تصل واتساب ولا نعرف جهازه، ورابطٌ لمتجرٍ
    //    لا يملكه طريقٌ مسدود في أول خطوة يطلبها منه.
    if (appLink || appLinkIos) {
        lines.push('', '*تحميل التطبيق*');
        if (appLink) lines.push(`أندرويد: ${appLink}`);
        if (appLinkIos) lines.push(`آيفون: ${appLinkIos}`);
    }
    if (support) {
        lines.push('', `أي استفسار أو مشكلة: ${support}`);
    }

    lines.push('', 'أهلاً بيك في الفريق.');

    return lines.join('\n');
}

/**
 * رسالة رفض الطلب.
 *
 * الرفض اليوم يُسجَّل في القاعدة ولا يبلَّغ به أحد — فينتظر المتقدّم أسابيع
 * ولا يعرف. والسبب مكتوبٌ أصلاً عند الرفض، فإخفاؤه عنه بلا فائدة.
 *
 * ونُبقي الباب مفتوحاً صراحةً: أغلب أسباب الرفض قابلة للإصلاح (صورة غير
 * واضحة، وثيقة ناقصة). «مرفوض» بلا طريقٍ للعودة تخسر كابتناً كان يصلح.
 *
 * @param {object} o {name, reason, supportPhone}
 */
function buildCaptainRejectionMessage(o) {
    const opts = o || {};
    const name = String(opts.name || '').trim() || 'الكابتن';
    const reason = String(opts.reason || '').trim();
    const support = localPhone(opts.supportPhone);

    const lines = [
        `*${name}، بخصوص طلب الانتساب لوجيز*`,
        '',
        'شكراً لوقتك. راجعنا طلبك، ولم نتمكّن من قبوله في الوقت الحالي.'
    ];

    if (reason) {
        lines.push('', '*السبب*', reason);
    }

    lines.push(
        '',
        '*يمكنك التقديم من جديد*',
        'إن كان السبب وثيقةً ناقصة أو صورة غير واضحة، صحّحها وقدّم مرة أخرى من التطبيق — طلبك سيُراجَع من جديد.'
    );

    if (support) {
        lines.push('', `للاستفسار أو الاعتراض: ${support}`);
    }

    lines.push('', 'نقدّر اهتمامك بالعمل معنا.');

    return lines.join('\n');
}

module.exports = { buildCaptainApprovalMessage, buildCaptainRejectionMessage, localPhone };

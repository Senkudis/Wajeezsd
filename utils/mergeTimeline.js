/**
 * 🔀 اقتطاع صفحةٍ من مصدرين مرتّبين زمنياً.
 *
 * «طلباتي» للعميل تُبنى من مجموعتين منفصلتين: `Order` (طلبات التوصيل)
 * و`ShopOrder` (طلبات المتاجر). ولأن لا وجود لـ JOIN بينهما، يُغري الحلُّ
 * السهل بتقسيم الصفحة **حسب المصدر**: نستنفد الأولى ثم نبدأ الثانية.
 *
 * وهذا بالضبط ما كان يحدث، وهو خطأ صامت وقاسٍ: يصير ترتيب القائمة الفعلي
 * «كل طلبات التوصيل، ثم كل طلبات المتاجر»، والفرز الزمني يُطبَّق داخل الصفحة
 * الواحدة فلا يُصلح شيئاً. عميلٌ له عشر طلبات توصيل لا يرى في صفحته الأولى
 * ولا طلب متجرٍ واحد — ولو أنشأه قبل ثانية — فيظنّ أن طلبه لم يُسجَّل.
 *
 * القاعدة التي يحرسها هذا الملف: **ادمج وافرز، ثم اقتطع**. لا العكس.
 *
 * @param {Array<{kind: string, doc: {createdAt: Date|string}}>} entries
 * @param {number} skip  عدد العناصر المتخطّاة من رأس القائمة المدموجة
 * @param {number} limit حجم الصفحة
 */
function slicePageByDate(entries, skip, limit) {
    return entries
        .slice()
        .sort((a, b) => new Date(b.doc.createdAt) - new Date(a.doc.createdAt))
        .slice(skip, skip + limit);
}

module.exports = { slicePageByDate };

/*
 * ════════════════════════════════════════════════════════════════
 *  coach.js — الشرح اللحظي عند ظهور شيء جديد
 * ════════════════════════════════════════════════════════════════
 *
 *  لماذا لا تكفي الجولة الترحيبية؟
 *  الجولة تشرح ما هو موجود لحظة الدخول، وأهمّ ما يحتاج شرحاً لا يكون
 *  موجوداً حينها. الكابتن يدخل أول مرّة بلا طلبات، فشرح "كيف تقبل
 *  الطلب" على شاشة فارغة كلامٌ بلا مرجع يُنسى قبل أن يصل أول طلب.
 *  والتاجر يدخل قبل أن يطلب منه أحد.
 *
 *  فالشرح يُؤجَّل إلى لحظته: أول طلب متاح يظهر ⇒ نشرح القبول عليه.
 *  أول مهمة تُقبل ⇒ نشرح الاستلام. أول طرد يُستلم ⇒ نشرح التسليم.
 *  كل تلميح مرّة واحدة لكل حساب، مربوطاً بالعنصر الحقيقي أمامه.
 *
 *  الاستعمال:
 *      Coach.fire('captain_first_order', '#orders-list > *');
 * ════════════════════════════════════════════════════════════════
 */
window.Coach = (function () {
    'use strict';

    /**
     * نصوص التلميحات. المفتاح ثابت لأنه يُخزَّن كعلامة "عُرض" —
     * تغييره يُعيد عرض التلميح لمن رآه.
     */
    const HINTS = {
        // ── الكابتن ────────────────────────────────────────────
        captain_first_order: {
            title: 'وصل أول طلب — هكذا تقبله',
            body: 'اضغط على البطاقة لترى التفاصيل: نقطة الاستلام، الوجهة، والأجرة. ثم "قبول الطلب" ليصبح لك.',
            note: 'إن رأيت الأجرة أقلّ من المسافة، أرسل عرضاً بسعر آخر بدل الرفض — للعميل أن يقبله.'
        },
        captain_first_mission: {
            title: 'الطلب صار مهمّتك — الخطوة التالية',
            body: 'توجّه لنقطة الاستلام، ثم اضغط "تم الاستلام" بعد أن تأخذ الطرد. الزر لا يعمل قبل وصولك للموقع.',
            note: 'اتصل بالعميل أو راسله من البطاقة نفسها إن لم تجد العنوان بدقّة.'
        },
        captain_first_pickup: {
            title: 'بحوزتك الطرد — أنهِ التوصيل',
            body: 'أوصِل الطرد للعنوان، وبعد تسليمه اضغط "تم التسليم". عندها تُحتسب أجرتك وتُغلق المهمة.',
            note: 'لا تؤجّل الضغط: المهمة تبقى مفتوحة والعميل يظنّها لم تُسلَّم بعد.'
        },
        captain_first_negotiation: {
            title: 'أرسلت عرض سعر',
            body: 'ينتظر عرضك ردّ العميل. إن قَبِل صار الطلب لك مباشرةً، وإن رفض أو انتهت المهلة يعود الطلب للجميع.'
        },

        // ── التاجر ─────────────────────────────────────────────
        merchant_first_order: {
            title: 'وصلك أول طلب — هكذا تنفّذه',
            body: 'اقبل الطلب أولاً، ثم جهّزه، ثم اضغط "جاهز" فيُطلب كابتن تلقائياً لاستلامه.',
            note: 'راجع الأصناف قبل القبول. إن نفد صنف راسل العميل بدل إلغاء الطلب كاملاً.'
        },
        merchant_first_ready: {
            title: 'الطلب جاهز — ما الذي يحدث الآن؟',
            body: 'أُرسل الطلب لكباتن مدينتك. سيصلك أحدهم لاستلامه، وتتابع حالته من تبويب "مع الكابتن".',
            note: 'يُسجَّل دخل البيع في حسابك لحظة تسليم الطلب للعميل لا لحظة تجهيزه.'
        },
        merchant_first_product: {
            title: 'أضفت أول منتج',
            body: 'صار متجرك قابلاً للتصفّح والطلب. أضف بقية أصنافك بالصورة والسعر لتكتمل واجهتك.',
            note: 'المنتج بلا صورة يُطلب أقلّ بكثير — صورة واضحة تكفي.'
        },

        // ── العميل ─────────────────────────────────────────────
        client_first_accept: {
            title: 'قَبِل كابتن طلبك',
            body: 'يمكنك متابعته على الخريطة لحظة بلحظة، ومراسلته أو الاتصال به من بطاقة الطلب.',
            note: 'إن تعذّر عليه الوصول للعنوان، رسالة قصيرة أسرع من إلغاء الطلب.'
        },
        client_first_offer: {
            title: 'وصلك عرض سعر من كابتن',
            body: 'رأى الكابتن أن الأجرة لا تناسب المسافة واقترح مبلغاً آخر. اقبله ليأخذ الطلب فوراً، أو ارفضه وانتظر كابتناً آخر.'
        },
        client_first_delivered: {
            title: 'وصل طلبك',
            body: 'قيّم الكابتن من بطاقة الطلب — تقييمك يرفع الكباتن الجيدين ويصل إليك أسرع في المرّة القادمة.'
        }
    };

    /**
     * يعرض التلميح إن لم يُعرض من قبل.
     * @param {string} key مفتاح من HINTS
     * @param {string} [el] محدّد العنصر المراد إبرازه
     * @returns {boolean} هل عُرض الآن
     */
    function fire(key, el) {
        const h = HINTS[key];
        if (!h || !window.WajeezTour) return false;
        return window.WajeezTour.hint({
            id: key,
            el: el || null,
            title: h.title,
            body: h.body,
            note: h.note,
            pad: 8
        });
    }

    /** هل عُرض هذا التلميح لهذا الحساب؟ */
    function seen(key) {
        return !!(window.WajeezTour && window.WajeezTour.isDone('hint_' + key));
    }

    /**
     * يطلق التلميح بعد أن يستقرّ العنصر في الصفحة.
     * الاستدعاء مباشرةً بعد innerHTML قد يسبق التخطيط، فتُقاس البؤرة
     * على عنصر بلا أبعاد وتُسقَط الخطوة.
     */
    function fireWhenReady(key, el, tries) {
        if (seen(key)) return;
        let left = tries == null ? 12 : tries;
        (function attempt() {
            const node = el ? document.querySelector(el) : null;
            if (!el || (node && node.getBoundingClientRect().height > 2)) {
                fire(key, el);
                return;
            }
            if (--left <= 0) return;
            setTimeout(attempt, 250);
        })();
    }

    const api = { fire, fireWhenReady, seen, HINTS };

    // 🔁 استبدال طابور config.js بالتنفيذ الحقيقي، ثم استنزاف ما تجمّع.
    // بهذا لا يهمّ أسبقَ نداءُ الصفحة تحميلَ هذا الملف أم تلاه.
    const queued = window.__coachQ || [];
    window.coachFire = function (key, selector) {
        fireWhenReady(key, selector);
    };
    queued.forEach(args => {
        try { fireWhenReady(args[0], args[1]); } catch (e) { /* لا نُسقط الصفحة لأجل شرح */ }
    });
    window.__coachQ = { push: args => window.coachFire(args[0], args[1]) };

    return api;
})();
